"""
Export all ADMET analysis results to CSV, pickle, and a markdown report.

Saves analysis objects (pickle) for downstream skills and a human-readable
markdown summary. (The PDF report is generated by the agent from these outputs —
see SKILL.md — not by this module.)
"""

import os
import pickle
import pandas as pd
from datetime import datetime


def export_all(results_df, summary, output_dir="results"):
    """
    Export all ADMET analysis results.

    Parameters
    ----------
    results_df : pd.DataFrame
        Full results from run_full_analysis().
    summary : dict
        Analysis summary dictionary.
    output_dir : str
        Directory to save all outputs.

    Outputs
    -------
    - all_properties.csv — Complete results table (all molecules × all properties)
    - druglikeness_summary.csv — Lipinski/Veber assessment
    - admet_predictions.csv — ADMET-AI predictions only
    - flagged_compounds.csv — Molecules with safety concerns
    - analysis_object.pkl — Pickle for downstream skills
    - analysis_report.md — Markdown summary report
    """
    os.makedirs(output_dir, exist_ok=True)

    print("\n" + "=" * 60)
    print("EXPORTING RESULTS")
    print("=" * 60)

    # 1. Full results table
    csv_path = os.path.join(output_dir, "all_properties.csv")
    results_df.to_csv(csv_path, index=False)
    print(f"   Saved: {csv_path} ({len(results_df)} molecules × {len(results_df.columns)} columns)")

    # 2. Drug-likeness summary (includes QED developability + structural-alert + sanity flags)
    druglike_cols = ["mol_id", "name", "smiles", "therapeutic_class", "MW", "LogP", "HBD", "HBA",
                     "TPSA", "RotatableBonds", "Lipinski_Violations", "Lipinski_Pass",
                     "Veber_Pass", "Druglike", "QED", "PAINS_Count", "PAINS_Pass",
                     "Toxicophore_Count", "sanity_flag"]
    available_cols = [c for c in druglike_cols if c in results_df.columns]
    druglike_df = results_df[available_cols].copy()
    druglike_path = os.path.join(output_dir, "druglikeness_summary.csv")
    druglike_df.to_csv(druglike_path, index=False)
    print(f"   Saved: {druglike_path}")

    # 2b. Structural alerts (PAINS + toxicophores) — feeds downstream triage
    alert_cols = ["mol_id", "name", "smiles", "QED", "PAINS_Count", "PAINS_Alerts",
                  "Toxicophore_Count", "Toxicophore_Alerts"]
    alert_cols = [c for c in alert_cols if c in results_df.columns]
    if "PAINS_Count" in results_df.columns:
        alert_path = os.path.join(output_dir, "structural_alerts.csv")
        results_df[alert_cols].to_csv(alert_path, index=False)
        print(f"   Saved: {alert_path}")

    # 3. ADMET predictions only
    admet_endpoints = summary.get("admet_endpoints", [])
    if admet_endpoints:
        admet_cols = ["name", "smiles"] + admet_endpoints
        admet_cols = [c for c in admet_cols if c in results_df.columns]
        admet_df = results_df[admet_cols].copy()
        admet_path = os.path.join(output_dir, "admet_predictions.csv")
        admet_df.to_csv(admet_path, index=False)
        print(f"   Saved: {admet_path} ({len(admet_endpoints)} endpoints)")

    # 4. Flagged compounds (safety concerns)
    flagged = _identify_flagged_compounds(results_df, summary)
    if not flagged.empty:
        flagged_path = os.path.join(output_dir, "flagged_compounds.csv")
        flagged.to_csv(flagged_path, index=False)
        print(f"   Saved: {flagged_path} ({len(flagged)} flagged molecules)")

    # 5. Analysis object (pickle) — CRITICAL for downstream skills
    analysis_obj = {
        "results_df": results_df,
        "summary": summary,
        "timestamp": datetime.now().isoformat(),
        "version": "1.0.0",
    }
    pkl_path = os.path.join(output_dir, "analysis_object.pkl")
    with open(pkl_path, "wb") as f:
        pickle.dump(analysis_obj, f)
    print(f"   Saved: {pkl_path}")
    print(f"   (Load with: obj = pickle.load(open('{pkl_path}', 'rb')))")

    # 6. Markdown report
    md_path = os.path.join(output_dir, "analysis_report.md")
    _write_markdown_report(results_df, summary, md_path)
    print(f"   Saved: {md_path}")

    print("\n=== Export Complete ===")
    print(f"All outputs saved to: {output_dir}/")


def _identify_flagged_compounds(results_df, summary):
    """Identify molecules with safety concerns."""
    flags = []

    for _, row in results_df.iterrows():
        reasons = []

        # Input-quality / standardization concern (non-drug-like or failed parent)
        sf = row.get("sanity_flag", "")
        if isinstance(sf, str) and sf:
            reasons.append(f"input: {sf}")

        # Check Lipinski violations
        if "Lipinski_Violations" in row and row["Lipinski_Violations"] >= 2:
            reasons.append(f"Lipinski violations: {int(row['Lipinski_Violations'])}")

        # PAINS = assay-interference substructure (hard triage flag)
        if "PAINS_Count" in row and pd.notna(row["PAINS_Count"]) and row["PAINS_Count"] >= 1:
            alerts = row.get("PAINS_Alerts", "") or "see structural_alerts.csv"
            reasons.append(f"PAINS: {alerts}")

        # Check safety endpoints
        safety = summary.get("safety_flags", {})
        for endpoint, info in safety.items():
            col = info["column"]
            val = pd.to_numeric(pd.Series([row.get(col)]), errors="coerce").iloc[0] if col in row else None
            if val is not None and pd.notna(val) and val > 0.5:
                reasons.append(f"{endpoint} positive (p={val:.2f})")

        if reasons:
            flags.append({
                "mol_id": row.get("mol_id", ""),
                "name": row["name"],
                "smiles": row["smiles"],
                "therapeutic_class": row.get("therapeutic_class", ""),
                "QED": round(row["QED"], 3) if "QED" in row and pd.notna(row.get("QED")) else "",
                "toxicophore_count": int(row["Toxicophore_Count"])
                    if "Toxicophore_Count" in row and pd.notna(row.get("Toxicophore_Count")) else "",
                "flags": "; ".join(reasons),
                "n_flags": len(reasons),
            })

    return pd.DataFrame(flags)


def _write_markdown_report(results_df, summary, output_path):
    """Write a markdown summary report."""
    n = summary["n_molecules"]
    n_dl = summary["n_druglike"]
    n_lip = summary["n_lipinski_pass"]
    n_veb = summary["n_veber_pass"]
    n_props = summary["n_properties"]
    endpoints = summary.get("admet_endpoints", [])
    mw = summary.get("mw_range", (0, 0))
    logp = summary.get("logp_range", (0, 0))

    lines = [
        "# ADMET Analysis Report",
        f"**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "",
        "## Summary",
        f"- **Molecules analyzed:** {n}",
        f"- **Total properties computed:** {n_props}",
        f"- **ADMET endpoints predicted:** {len(endpoints)}",
        f"- **Drug-like (Lipinski + Veber):** {n_dl}/{n} ({100*n_dl/n:.0f}%)" if n > 0 else "",
    ]
    if "qed_mean" in summary:
        lines.append(f"- **Mean QED (developability):** {summary['qed_mean']:.2f} "
                     f"({summary.get('n_qed_ge_05', 0)}/{n} with QED ≥ 0.5)")
    if "n_pains" in summary:
        lines.append(f"- **PAINS-flagged:** {summary['n_pains']}/{n}  •  "
                     f"**Toxicophore-flagged:** {summary.get('n_toxicophore', 0)}/{n}  •  "
                     f"**Alert-free:** {summary.get('n_alert_free', 0)}/{n}")
    if "n_sanity_flagged" in summary:
        lines.append(f"- **Input quality:** {summary.get('n_sanity_flagged', 0)}/{n} flagged "
                     f"non-drug-like (sanity_flag); "
                     f"{summary.get('n_standardization_failed', 0)} failed standardization "
                     "(desalted/neutralized/de-duplicated upstream)")
    lines.extend([
        "",
        "## Physicochemical Properties",
        f"- MW range: {mw[0]:.0f} – {mw[1]:.0f} Da",
        f"- LogP range: {logp[0]:.1f} – {logp[1]:.1f}",
        f"- Lipinski Ro5 pass: {n_lip}/{n}",
        f"- Veber pass: {n_veb}/{n}",
        "",
        "## Drug-Likeness Assessment",
        "",
    ])

    # Cap the per-compound table for large lists (full data is in the CSVs)
    table_max = 30
    table_df = results_df
    if len(results_df) > table_max and "QED" in results_df.columns:
        table_df = results_df.sort_values("QED", ascending=False).head(table_max)
        lines.append(f"*Showing top {table_max} of {len(results_df)} by QED "
                     "(full table in `druglikeness_summary.csv`).*")
        lines.append("")

    lines.extend([
        "| Drug | MW | LogP | QED | Lipinski Viol. | PAINS | Drug-like |",
        "|------|-----|------|-----|----------------|-------|-----------|",
    ])

    for _, row in table_df.iterrows():
        dl = "Yes" if row.get("Druglike", False) else "No"
        lv = int(row.get("Lipinski_Violations", 0)) if pd.notna(row.get("Lipinski_Violations")) else 0
        qed = f"{row['QED']:.2f}" if "QED" in row and pd.notna(row.get("QED")) else "—"
        pc = row.get("PAINS_Count", 0)
        pains = str(int(pc)) if pd.notna(pc) else "—"
        mw = f"{row['MW']:.0f}" if pd.notna(row.get("MW")) else "—"
        logp = f"{row['LogP']:.1f}" if pd.notna(row.get("LogP")) else "—"
        lines.append(f"| {row['name']} | {mw} | {logp} | {qed} | {lv} | {pains} | {dl} |")

    # Structural alerts section
    if "n_pains" in summary:
        lines.extend([
            "",
            "## Structural Alerts",
            "",
            f"- **PAINS** (assay-interference substructures, Baell & Holloway 2010): "
            f"{summary['n_pains']}/{n} compounds flagged — treat as a triage *exclusion* signal.",
            f"- **Toxicophores** (Brenk/NIH unwanted groups): "
            f"{summary.get('n_toxicophore', 0)}/{n} compounds — *advisory*; many approved "
            f"drugs carry one. See `structural_alerts.csv` for per-compound substructures.",
        ])

    lines.extend(["", "## Safety Flags", ""])
    safety = summary.get("safety_flags", {})
    if safety:
        lines.append("| Endpoint | Flagged Compounds | Column |")
        lines.append("|----------|-------------------|--------|")
        for endpoint, info in safety.items():
            lines.append(f"| {endpoint} | {info['n_flagged']} | {info['column']} |")
    else:
        lines.append("No safety flags identified (ADMET predictions may not be available).")

    lines.extend([
        "",
        "## Methods",
        "- **Standardization:** RDKit MolStandardize — desalt (FragmentParent), neutralize (Uncharger), "
        "canonicalize (isomeric); de-duplicated by structure; non-drug-like parents flagged (not dropped)",
        "- **Physicochemical descriptors:** RDKit (MW, LogP, HBD, HBA, TPSA, RotatableBonds, AromaticRings, FractionCSP3)",
        "- **Drug-likeness:** Lipinski Rule of Five (≤1 violation), Veber rules, QED (Bickerton 2012)",
        "- **Structural alerts:** RDKit FilterCatalog — PAINS (Baell 2010), Brenk (2008), NIH",
        "- **ADMET predictions:** ADMET-AI (Chemprop-RDKit ensemble, trained on TDC benchmarks)",
        "",
        "## Output Files",
        "- `all_properties.csv` — Complete results (all molecules × all properties)",
        "- `druglikeness_summary.csv` — Lipinski/Veber/QED assessment + alert flags",
        "- `structural_alerts.csv` — Per-compound PAINS + toxicophore substructures",
        "- `admet_predictions.csv` — ADMET endpoint predictions",
        "- `flagged_compounds.csv` — Molecules with safety/triage concerns",
        "- `analysis_object.pkl` — Analysis object for downstream use",
        "",
        "---",
        "*Generated by molecular-property-admet skill*",
    ])

    with open(output_path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    print("Run via the main workflow — not standalone.")
